export const fmtNum = (n, digits = 0) =>
  new Intl.NumberFormat(lang, { maximumFractionDigits: digits }).format(n);

export const fmtMoney = (n) =>
  new Intl.NumberFormat(lang, {
    style: "currency",
    currency: CONFIG.currency,
    maximumFractionDigits: Math.abs(n) >= 1000 ? 0 : 2,
  }).format(n);

/** style: "short" → "24 de set." · "day" → "24 de setembre" · "long" → "Dijous, 24 de setembre" */
export function fmtDate(date, style = "short") {
  const options = {
    short: { day: "numeric", month: "short" },
    day: { day: "numeric", month: "long" },
    long: { weekday: "long", day: "numeric", month: "long" },
  }[style];
  const text = new Intl.DateTimeFormat(lang, options).format(new Date(date));
  return style === "long" ? text.charAt(0).toUpperCase() + text.slice(1) : text;
}

export const fmtTime = (date) => new Intl.DateTimeFormat(lang, { hour: "2-digit", minute: "2-digit" }).format(new Date(date));

/** -2 → "fa 2 dies" / "hace 2 días" / "2 days ago"; 0 → "avui"; 1 → "demà". */
export const fmtRel = (days) => new Intl.RelativeTimeFormat(lang, { numeric: "auto" }).format(days, "day");
